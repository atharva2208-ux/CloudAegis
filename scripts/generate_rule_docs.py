#!/usr/bin/env python3
"""Generate docs/detection-rules.md from the rule registry.

The rule metadata in code is the single source of truth; this keeps the
documentation from drifting. ``--check`` exits non-zero if the file is stale.
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages" / "security-engine"))

from cloudaegis_engine.compliance.catalog import controls_for_rule  # noqa: E402
from cloudaegis_engine.models import Severity  # noqa: E402
from cloudaegis_engine.resource_types import SERVICE_ORDER  # noqa: E402
from cloudaegis_engine.rules import default_registry  # noqa: E402

OUT = ROOT / "docs" / "detection-rules.md"


def anchor(rule_id: str) -> str:
    return rule_id.lower()


def render() -> str:
    rules = default_registry().all()
    by_service: dict[str, list] = defaultdict(list)
    for rule in rules:
        by_service[rule.metadata.service].append(rule)
    services = [s for s in SERVICE_ORDER if s in by_service] + sorted(set(by_service) - set(SERVICE_ORDER))
    sev_counts = {s.value: sum(1 for r in rules if r.metadata.severity is s) for s in Severity.ordered()}

    lines = [
        "# Detection rules",
        "",
        "<!-- Generated by scripts/generate_rule_docs.py from the rule registry. Do not edit by hand. -->",
        "",
        f"CloudAegis ships **{len(rules)} detection rules** across {len(services)} AWS services. Every rule is a small, "
        "independently tested class that evaluates one normalized resource and returns PASS or FAIL with evidence "
        "(or nothing when the rule does not apply). Rules are read-only: they inspect configuration collected during "
        "discovery and never call AWS themselves.",
        "",
        "| Severity | Rules |",
        "|---|---|",
        *[f"| {s.title()} | {n} |" for s, n in sev_counts.items()],
        "",
        "Severity drives the [security score](security-model.md#security-score) weights "
        "(critical 10, high 5, medium 2, low 1, info 0).",
        "",
        "## Index",
        "",
        "| ID | Title | Severity | Resource |",
        "|---|---|---|---|",
    ]
    for service in services:
        for rule in by_service[service]:
            m = rule.metadata
            lines.append(f"| [{m.rule_id}](#{anchor(m.rule_id)}) | {m.title} | {m.severity.value} | `{m.resource_type}` |")
    for service in services:
        lines += ["", f"## {service}", ""]
        for rule in by_service[service]:
            m = rule.metadata
            mappings = controls_for_rule(m.rule_id)
            lines += [
                f"### {m.rule_id}",
                "",
                f"**{m.title}**",
                "",
                f"- Severity: **{m.severity.value}**",
                f"- Category: {m.category}",
                f"- Resource type: `{m.resource_type}`",
                f"- Compliance: {', '.join(f'{fw.short_name} {c.control_id}' for fw, c in mappings) or '—'}",
                "",
                f"**What it checks.** {m.description}",
                "",
                f"**Why it matters.** {m.impact}",
                "",
                f"**Remediation.** {m.remediation}",
                "",
            ]
            steps = [s for s in m.remediation_steps if s != m.remediation]
            if steps:
                lines += [f"{i}. {s}" for i, s in enumerate(steps, 1)] + [""]
            if m.remediation_cli:
                lines += ["Example (review before running; CloudAegis never runs it):", "", "```bash", m.remediation_cli, "```", ""]
            if m.references:
                lines += ["References: " + " · ".join(f"<{r}>" for r in m.references), ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if docs/detection-rules.md is out of date")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != content:
            print("docs/detection-rules.md is stale; run scripts/generate_rule_docs.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content)
    print(f"wrote {OUT.relative_to(ROOT)} ({content.count('### ')} rules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
